import Foundation

/// renders collected provenance as Swift source, and writes it without
/// touching the file when the rendered text has not changed.
///
/// the rendered file is pure data — one constant per field — so the logic that
/// consumes it (version composition, diagnostics) stays hand-written and
/// reviewable rather than generated.
public enum GitMetadataRenderer {
    /// the type the rendered file declares.
    public static let typeName = "GitProvenance"

    /// the generated Swift source for `metadata`.
    ///
    /// deterministic: the same metadata always renders byte-identical text, so
    /// a no-op build never rewrites the file (and never recompiles the target).
    public static func swiftSource(for metadata: GitMetadata) -> String {
        var lines: [String] = []
        lines.append("// generated by git-metadata-tool. do not edit.")
        lines.append("// one constant per field; nil means the value was unavailable at")
        lines.append("// build time (no repository, no git, or no commits yet).")
        lines.append("public enum \(typeName) {")
        lines.append("    /// full commit hash, 40 hex characters")
        lines.append("    public static let commitHash: String? = \(literal(metadata.commitHash))")
        lines.append("    /// abbreviated commit hash")
        lines.append("    public static let shortCommitHash: String? = \(literal(metadata.shortCommitHash))")
        lines.append("    /// current branch, nil on a detached HEAD")
        lines.append("    public static let branch: String? = \(literal(metadata.branch))")
        lines.append("    /// nearest reachable tag, nil when the commit is untagged")
        lines.append("    public static let tag: String? = \(literal(metadata.tag))")
        lines.append("    /// `git describe --tags --always`")
        lines.append("    public static let describe: String? = \(literal(metadata.describe))")
        lines.append("    /// committer date of HEAD, ISO-8601")
        lines.append("    public static let commitDate: String? = \(literal(metadata.commitDate))")
        lines.append("    /// commits reachable from HEAD")
        lines.append("    public static let commitCount: Int? = \(metadata.commitCount.map(String.init) ?? "nil")")
        lines.append("    /// true when the working tree had local changes at build time")
        lines.append("    public static let isDirty: Bool = \(metadata.isDirty)")
        lines.append("}")
        return lines.joined(separator: "\n") + "\n"
    }

    /// a `key: value` dump of every field, for `--print` and for tests.
    /// unavailable fields print as `-`.
    public static func text(_ metadata: GitMetadata) -> String {
        func field(_ value: String?) -> String { value ?? "-" }
        let lines = [
            "commitHash: \(field(metadata.commitHash))",
            "shortCommitHash: \(field(metadata.shortCommitHash))",
            "branch: \(field(metadata.branch))",
            "tag: \(field(metadata.tag))",
            "describe: \(field(metadata.describe))",
            "commitDate: \(field(metadata.commitDate))",
            "commitCount: \(metadata.commitCount.map(String.init) ?? "-")",
            "isDirty: \(metadata.isDirty)",
        ]
        return lines.joined(separator: "\n") + "\n"
    }

    /// a Swift string literal for `value`, or `nil` when it is absent.
    static func literal(_ value: String?) -> String {
        guard let value else { return "nil" }
        return "\"\(escaped(value))\""
    }

    /// escape a string for inclusion in a Swift source literal. git ref names
    /// may contain quotes and other surprising characters, so nothing is
    /// passed through unescaped.
    static func escaped(_ value: String) -> String {
        var out = ""
        for scalar in value.unicodeScalars {
            switch scalar {
            case "\\": out += "\\\\"
            case "\"": out += "\\\""
            case "\n": out += "\\n"
            case "\r": out += "\\r"
            case "\t": out += "\\t"
            default:
                if scalar.value < 0x20 || scalar.value == 0x7F {
                    out += "\\u{\(String(scalar.value, radix: 16))}"
                } else {
                    out.unicodeScalars.append(scalar)
                }
            }
        }
        return out
    }

    /// write `contents` to `path` unless the file already holds exactly that
    /// text.
    ///
    /// returning whether a write happened lets a build-tool caller stay quiet
    /// on a no-op build — and keeps the file's mtime stable, so the build
    /// system does not recompile the target that consumes it.
    @discardableResult
    public static func writeIfChanged(_ contents: String, to path: String) throws -> Bool {
        let url = URL(fileURLWithPath: path)
        if let existing = try? String(contentsOf: url, encoding: .utf8), existing == contents {
            return false
        }
        try FileManager.default.createDirectory(
            at: url.deletingLastPathComponent(), withIntermediateDirectories: true
        )
        try contents.write(to: url, atomically: true, encoding: .utf8)
        return true
    }
}