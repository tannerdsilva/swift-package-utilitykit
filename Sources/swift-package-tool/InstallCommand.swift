/// install the package's binaries and (optionally) a harness adapter onto the host.
///
/// port of the former `scripts/install.sh`: checks prerequisites, builds the
/// requested configuration, installs `swift-package-tool` and
/// `normalizer-tool` into the install dir (with sudo escalation when the dir
/// isn't writable), writes the harness adapter — the plugin manifest generated
/// by the *installed* binary (`plugin --mcp-manifest arc`), so the tool table
/// can never drift from the compiled surface — when a plugins dir is given,
/// wires the install dir into the harness PATH, and verifies the result.
/// the CLI itself is harness-agnostic: it assumes, names, and probes no
/// harness unless a plugins dir is explicitly requested.
struct InstallCommand: AsyncParsableCommand {
    static let configuration = CommandConfiguration(
        commandName: "install",
        abstract: "Build and install the binaries and the harness adapter."
    )

    @Flag(name: .customLong("debug"), help: "Install debug binaries instead of release.")
    var debug = false

    @Flag(name: .customLong("no-build"), help: "Skip the swift build step (use prebuilt binaries).")
    var noBuild = false

    @Flag(name: .customLong("no-path-update"), help: "Skip wiring the install dir into the harness PATH.")
    var noPathUpdate = false

    @Flag(name: .customLong("no-interactive"), help: "Never prompt; fail on missing choices instead.")
    var noInteractive = false

    @Option(name: .customLong("prefix"), help: "Parent directory for binaries (default: ~/.local).")
    var prefix: String?

    @Option(name: .customLong("bin-dir"), help: "Exact binary install dir (overrides --prefix/bin).")
    var binDir: String?

    @Option(name: .customLong("build-dir"), help: "Directory containing prebuilt binaries (default: <repo>/.build/<config>).")
    var buildDirOverride: String?

    @Option(name: .customLong("plugins-dir"), help: "Write the harness plugin manifest (generated by `plugin --mcp-manifest arc`) into this directory (omit to skip).")
    var pluginsDirOverride: String?

    mutating func run() async throws {
        let env = ProcessInfo.processInfo.environment
        let home = PathWirer.homeDir()

        // ---- resolve configuration -------------------------------------------------

        let installDir: String
        if let explicit = binDir ?? env["BIN_DIR"], !explicit.isEmpty {
            installDir = explicit
        } else {
            let pfx = prefix ?? env["PREFIX"] ?? "\(home)/.local"
            installDir = "\(pfx)/bin"
        }

        // the harness adapter installs only into an explicitly requested
        // directory — the CLI assumes no harness layout, so an unset
        // --plugins-dir/PLUGINS_DIR means "skip the adapter step".
        let pluginsDir: String? = [pluginsDirOverride, env["PLUGINS_DIR"]]
            .compactMap { $0 }
            .first { !$0.isEmpty }
        let pluginName = "swift-package-utilitykit"
        let pluginDst = pluginsDir.map { "\($0)/\(pluginName)" }

        let pathUpdate = !noPathUpdate && env["PATH_UPDATE"] != "0"
        let interactive = !noInteractive && isInteractive() && env["NO_INTERACTIVE"] != "1"

        // ---- prerequisites ---------------------------------------------------------

        InstPrinter.info("Installing swift-package-utilitykit...")
        InstPrinter.info("Checking prerequisites...")

        guard let swiftVersion = await runCapture("/usr/bin/env", ["swift", "--version"]) else {
            throw ValidationError("Swift toolchain not found. Install Swift 6.0+ from https://swift.org/download/")
        }
        let versionLine = swiftVersion.split(separator: "\n").first.map(String.init) ?? ""
        InstPrinter.ok("\(versionLine)")

        // ---- build -----------------------------------------------------------------

        let config = debug ? "debug" : "release"

        // where the prebuilt products live. `--build-dir`/BUILD_DIR overrides
        // the default `<repo>/.build/<config>` — needed when binaries were
        // built into a scratch workspace (e.g. nested builds that must not
        // share the package's build lock) rather than the repo's own `.build`.
        let buildSrcDir: String
        if let explicit = buildDirOverride ?? env["BUILD_DIR"], !explicit.isEmpty {
            buildSrcDir = explicit
        } else {
            buildSrcDir = "\(repoDir())/.build/\(config)"
        }

        if noBuild {
            InstPrinter.info("Using prebuilt \(config) binaries (--no-build)...")
            // verify the prebuilt binaries actually exist — a stale or missing
            // build must be a hard error, never a silent no-op install
            for bin in ["swift-package-tool", "normalizer-tool"] {
                let src = "\(buildSrcDir)/\(bin)"
                guard FileManager.default.fileExists(atPath: src) else {
                    throw ValidationError("prebuilt binary not found at \(src) — run `swift build -c \(config)` first, or drop --no-build")
                }
            }
        } else {
            InstPrinter.info("Building \(config) binaries...")
            let (buildStatus, buildLog) = await runBuildCaptured(config, repo: repoDir())
            print(buildLog)
            guard buildStatus == 0 else {
                throw ValidationError("swift build -c \(config) failed; install aborted")
            }
            InstPrinter.ok("Build complete")
        }

        // ---- install binaries -------------------------------------------------------

        InstPrinter.info("Installing binaries to \(installDir)...")
        if let sudo = needSudo(for: installDir) {
            InstPrinter.info("using sudo for \(installDir) (not writable by current user)")
        }
        if interactive {
            print("  Install binaries to \(installDir)? [Y/n] ", terminator: "")
            if let answer = readLine()?.lowercased(), answer != "y", answer != "yes", !answer.isEmpty {
                InstPrinter.info("Cancelled.")
                return
            }
        }
        var mkdirCmd = [String]()
        if let s = needSudo(for: installDir) { mkdirCmd.append(s) }
        mkdirCmd += ["mkdir", "-p", installDir]
        if await runProcess("/usr/bin/env", mkdirCmd) != 0 {
            throw ValidationError("failed to create install dir \(installDir)")
        }

        for bin in ["swift-package-tool", "normalizer-tool"] {
            var icmd = [String]()
            if let s = needSudo(for: installDir) { icmd.append(s) }
            icmd += ["install", "\(buildSrcDir)/\(bin)", "\(installDir)/\(bin)"]
            if await runProcess("/usr/bin/env", icmd) != 0 {
                throw ValidationError("failed to install \(bin) (\(buildSrcDir)/\(bin) -> \(installDir)/\(bin))")
            }
            InstPrinter.ok("  \(installDir)/\(bin)")
        }

        // ---- install harness adapter --------------------------------------------------

        if let pluginsDir, let pluginDst {
            try FileManager.default.createDirectory(atPath: pluginsDir, withIntermediateDirectories: true)

            // remove a previous adapter (dir, or a symlink from an older
            // install) — a failed replace must be a hard error, never a
            // silent half-install
            if FileManager.default.fileExists(atPath: pluginDst) || isSymlink(pluginDst) {
                do {
                    try FileManager.default.removeItem(atPath: pluginDst)
                } catch {
                    throw ValidationError("failed to remove previous adapter at \(pluginDst): \(error)")
                }
                InstPrinter.ok("  Removed previous adapter at \(pluginDst)")
            }

            // the manifest is generated BY the installed binary, so the tool
            // table compiled into it is the single source of truth.
            InstPrinter.info("Installing harness adapter (generated manifest)...")
            guard let manifest = await runCapture("\(installDir)/swift-package-tool", ["plugin", "--mcp-manifest", "arc"], env: env),
                  let data = manifest.data(using: .utf8),
                  let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
                  let tools = json["tools"] as? [[String: Any]], !tools.isEmpty else {
                throw ValidationError("failed to generate the manifest from \(installDir)/swift-package-tool plugin --mcp-manifest arc")
            }
            do {
                try FileManager.default.createDirectory(atPath: pluginDst, withIntermediateDirectories: true)
                try manifest.write(toFile: "\(pluginDst)/manifest.json", atomically: true, encoding: .utf8)
            } catch {
                throw ValidationError("failed to write manifest (\(pluginDst)/manifest.json): \(error)")
            }
            InstPrinter.ok("  manifest written: \(pluginDst)/manifest.json (\(tools.count) tools)")
        } else {
            InstPrinter.info("Skipping harness adapter (no --plugins-dir / PLUGINS_DIR given).")
        }

        // ---- wire install dir into harness PATH --------------------------------------

        if pathUpdate {
            InstPrinter.info("Wiring \(installDir) into the harness PATH...")
            if PathWirer.isOnLivePATH(installDir) {
                PathWirer.printInfo("  already on PATH: \(installDir)")
            } else {
                try? PathWirer.add(installDir)
            }
        } else {
            InstPrinter.warn("PATH wiring skipped (PATH_UPDATE=0). Add \(installDir) to your shell PATH manually.")
        }

        // ---- verify -----------------------------------------------------------------

        InstPrinter.info("Verifying installation...")
        var envExtra = ProcessInfo.processInfo.environment
        envExtra["PATH"] = "\(installDir):\(envExtra["PATH"] ?? "")"
        if let ver = await runCapture("\(installDir)/swift-package-tool", ["--version"], env: envExtra) {
            InstPrinter.ok("  swift-package-tool \(ver.trimmingCharacters(in: .whitespacesAndNewlines))")
        } else {
            InstPrinter.warn("  swift-package-tool not found in PATH. Add \(installDir) to your PATH.")
        }

        print("")
        print("\u{001B}[32m✓ Installation complete!\u{001B}[0m")
        print("")
        print("  Binaries:  \(installDir)/{swift-package-tool,normalizer-tool}")
        if let pluginDst {
            print("  Adapter:   \(pluginDst)/manifest.json (plugin manifest)")
        } else {
            print("  Adapter:   (skipped — no --plugins-dir)")
        }
        print("")
        print("  Next steps:")
        print("    1. Open a new shell (or restart your agent harness) so the wired PATH takes effect")
        print("    2. Verify binaries:         swift-package-tool --version")
        if pluginsDir != nil {
            print("    3. Activate in the harness: reload its plugin registry (manifest: \(pluginName))")
        }
    }

    /// the package repo root: walk up from cwd until a directory with a
    /// Package.swift + this repo's own target dir is found (an agent may run
    /// install from anywhere, not just the repo root).  the markers are the
    /// repo's own identity — never an adapter directory, which is free to be
    /// renamed or joined by siblings.  falls back to cwd; downstream
    /// existence checks then fail loudly instead of silently copying nothing.
    func repoDir() -> String {
        let fm = FileManager.default
        var dir = URL(fileURLWithPath: fm.currentDirectoryPath)
        for _ in 0..<8 {
            let hasManifest = fm.fileExists(atPath: dir.appendingPathComponent("Package.swift").path)
            let hasTool = fm.fileExists(atPath: dir.appendingPathComponent("Sources/swift-package-tool").path)
            if hasManifest && hasTool {
                return dir.path
            }
            let parent = dir.deletingLastPathComponent()
            if parent == dir { break }
            dir = parent
        }
        return fm.currentDirectoryPath
    }
}

/// human-facing installer output (matches the former bash printer).
enum InstPrinter {
    static func info(_ s: String) { print("\u{001B}[36m==>\u{001B}[0m \(s)") }
    static func ok(_ s: String) { print("\u{001B}[32m  OK\u{001B}[0m  \(s)") }
    static func warn(_ s: String) { print("\u{001B}[33m  WARN\u{001B}[0m \(s)") }
}

/// true if the nearest existing ancestor of `dir` is not writable by the
/// current user (mirrors the bash walk-up escalation).
func needSudo(for dir: String) -> String? {
    var ancestor = dir
    while ancestor != "/" && !FileManager.default.fileExists(atPath: ancestor) {
        ancestor = (ancestor as NSString).deletingLastPathComponent
    }
    if ancestor.isEmpty { ancestor = "/" }
    guard FileManager.default.isWritableFile(atPath: ancestor) else {
        InstPrinter.info("using sudo for \(dir) (not writable by current user)")
        return "sudo"
    }
    return nil
}

/// is `path` a symlink?
func isSymlink(_ path: String) -> Bool {
    (try? FileManager.default.destinationOfSymbolicLink(atPath: path)) != nil
}

/// run a command to completion; the exit code, or nil when it could not be
/// launched at all.
func runProcess(_ executable: String, _ args: [String], cwd: String? = nil, env: [String: String]? = nil) async -> Int32? {
    do {
        let outcome = try await Subprocess.capture(
            executable, args, workingDirectory: cwd, environment: env)
        return outcome.exitCode
    } catch {
        return nil
    }
}

/// run `swift build -c <config>` and capture the log.
/// returns (exit status, trimmed log tail).  a failed build surfaces as non-zero
/// — the installer must never report "build complete" when the build failed.
func runBuildCaptured(_ config: String, repo: String) async -> (Int32, String) {
    do {
        let outcome = try await Subprocess.capture(
            "/usr/bin/env", ["swift", "build", "-c", config], workingDirectory: repo)
        // stderr is shown after stdout: for a failed build the compiler's
        // errors are on stderr, so they stay in the tail the caller prints.
        let log = outcome.stdout + outcome.stderr
        let trimmed = log.split(separator: "\n").suffix(5).joined(separator: "\n")
        return (outcome.exitCode, trimmed)
    } catch {
        return (1, "failed to launch swift build: \(error)")
    }
}

/// run a command and return its stdout, or its merged output when it failed.
/// nil when the command could not be launched.
func runCapture(_ executable: String, _ args: [String], cwd: String? = nil, env: [String: String]? = nil) async -> String? {
    do {
        let outcome = try await Subprocess.capture(
            executable, args, workingDirectory: cwd, environment: env)
        guard outcome.exitCode == 0 else {
            return outcome.stdout + outcome.stderr
        }
        return outcome.stdout
    } catch {
        return nil
    }
}
